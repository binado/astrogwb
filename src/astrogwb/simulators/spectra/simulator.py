"""The simulator that reduces drawn populations to spectral densities.

A spectrum is a population draw reduced through a waveform. The population half
-- hyperparameters, exact count, sources -- is
:class:`~astrogwb.simulators.population.PopulationSimulator`; the waveform half
is :class:`~astrogwb.simulators.spectra.forward.ChunkedPowerSum`, which sums the
draw's events chunk by chunk. :class:`BackgroundSpectralDensitySimulator` owns
only the waveform half, built once from a
:class:`BackgroundSpectralDensityMetadata`, so a loop that calls it again reuses
every compilation; callers compose it with a population simulator, so one
population can meet several approximants.

One key is one draw, hyperparameters and sources alike, so the population at
key ``k`` is the same whether it is asked for first or last in a loop.
:class:`BackgroundSpectralDensityData` always has a leading draw axis, including
for one draw. :func:`stack_spectra` concatenates results along that axis; the
same layout is used in memory and in files, with metadata kept separately.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any, TypedDict

import jax
import numpy as np
from numpy.typing import NDArray

from astrogwb import __version__
from astrogwb.populations import joint_model
from astrogwb.simulators.population.simulator import PopulationData
from astrogwb.simulators.spectra.forward import (
    ChunkedPowerSum,
    normalize_spectra,
    validate_source_model,
)
from astrogwb.simulators.spectra.metadata import BackgroundSpectralDensityMetadata
from astrogwb.utils import years_to_seconds

__all__ = [
    "BackgroundSpectralDensityData",
    "BackgroundSpectralDensitySimulator",
    "stack_spectra",
]


class BackgroundSpectralDensityData(TypedDict):
    """Background spectral-density draws, with a leading draw axis.

    ``frequencies`` is ``(F,)`` and shared by the batch. ``spectral_density`` is
    ``(D, F)``; ``n_events``, ``total_merger_rate`` and every ``hyperparameters``
    column are ``(D,)``. A simulator call or reduction has ``D=1``;
    :func:`stack_spectra` concatenates draws without adding another axis.
    """

    frequencies: NDArray[np.float64]
    spectral_density: NDArray[np.float64]
    n_events: NDArray[np.int64]
    total_merger_rate: NDArray[np.float64]
    hyperparameters: dict[str, NDArray[np.float64]]


class BackgroundSpectralDensitySimulator:
    """Draws spectra from :class:`BackgroundSpectralDensityMetadata`.

    Build once and call often. ``simulator(population)`` pushes an already-drawn
    :class:`~astrogwb.simulators.population.PopulationData` through this
    waveform and returns :class:`BackgroundSpectralDensityData` with one row;
    draw the population with
    :class:`~astrogwb.simulators.population.PopulationSimulator`, loop over
    :func:`~astrogwb.simulators.core.batch_keys`, and join with
    :func:`stack_spectra` for several draws.

    Building runs the one-off work: the waveform generator and
    :func:`~astrogwb.simulators.spectra.forward.validate_source_model` at a
    representative point -- the fixed values and each prior's mean. Values are
    checked once, eagerly: generation is trace-safe and trusts its inputs, so a
    population carrying a degree of freedom the approximant cannot represent
    would otherwise be silently dropped. ``chunk_size`` chunks the waveform
    reduction: peak waveform memory is ``(F, chunk_size)``.

    ``validate_sources=False`` skips that check. It exists for a deliberate
    comparison across approximants that carry fewer degrees of freedom than a
    population has -- a tidal population through a non-tidal waveform, whose
    generator then ignores the deformabilities -- and is never the right choice
    for a record that is persisted, since the dropped columns would not show.
    """

    def __init__(
        self,
        metadata: BackgroundSpectralDensityMetadata,
        *,
        chunk_size: int = 128,
        validate_sources: bool = True,
    ) -> None:
        # x64 before any array: the rate evaluation and the draws must not
        # depend on ripplegw's import turning it on as a side effect.
        jax.config.update("jax_enable_x64", True)

        if chunk_size <= 0:
            raise ValueError("chunk_size must be positive")
        if metadata.version != __version__:
            raise ValueError(
                f"metadata is for astrogwb {metadata.version}, but {__version__} "
                "is installed; draws are generated by the code their key names"
            )
        self._metadata = metadata
        self._observation_seconds = years_to_seconds(metadata.observation_time)
        self._generator = metadata.waveform.build()
        self._reducer = ChunkedPowerSum(self._generator, chunk_size=chunk_size)

        if validate_sources:
            model = joint_model(
                *metadata.population.build()(
                    {
                        **metadata.fixed,
                        **{
                            name: float(prior.build().mean)
                            for name, prior in metadata.sampled.items()
                        },
                    }
                )
            )
            validate_source_model(
                model,
                generator=self._generator,
                rng_key=jax.random.key(0),
            )

    @property
    def metadata(self) -> BackgroundSpectralDensityMetadata:
        """The record this simulator draws."""
        return self._metadata

    def __call__(self, population: PopulationData) -> BackgroundSpectralDensityData:
        """The spectrum of ``population``, as drawn by a population simulator."""
        sources = dict(population["source_parameters"])
        count = int(population["count"])
        rate = np.asarray(population["total_merger_rate"])
        density = normalize_spectra(
            self._reducer(sources),
            count=self._metadata.count,
            total_merger_rate=rate,
            observation_seconds=self._observation_seconds,
            num_events=self._metadata.num_events,
        )
        return {
            "frequencies": np.asarray(self._generator.frequencies),
            "spectral_density": density[np.newaxis, :],
            "n_events": np.asarray([count], dtype=np.int64),
            "total_merger_rate": rate[np.newaxis],
            "hyperparameters": {
                name: np.asarray(value)[np.newaxis]
                for name, value in population["hyperparameters"].items()
            },
        }


def stack_spectra(
    parts: Sequence[BackgroundSpectralDensityData],
) -> BackgroundSpectralDensityData:
    """Concatenate spectra along their existing leading draw axis.

    The non-empty sequence must share one frequency grid and hyperparameter
    names. Construction guarantees matching column shapes; the result keeps
    the first grid once, without re-validating the data.
    """

    def stack(name: str) -> NDArray[Any]:
        return np.concatenate([part[name] for part in parts], axis=0)  # ty: ignore[invalid-key]

    return {
        "frequencies": parts[0]["frequencies"],
        "spectral_density": stack("spectral_density"),
        "n_events": stack("n_events"),
        "total_merger_rate": stack("total_merger_rate"),
        "hyperparameters": {
            name: np.concatenate(
                [part["hyperparameters"][name] for part in parts], axis=0
            )
            for name in parts[0]["hyperparameters"]
        },
    }
